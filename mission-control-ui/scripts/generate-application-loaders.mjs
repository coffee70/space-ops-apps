import fs from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const applicationsRoot = path.join(projectRoot, "src", "applications");
const outputPath = path.join(
  projectRoot,
  "src",
  "platform",
  "registry",
  "application-loader-manifest.generated.ts",
);
const checkMode = process.argv.includes("--check");

function getGeneratedManifestSource() {
  const applicationDirs = fs
    .readdirSync(applicationsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((entry) => fs.existsSync(path.join(applicationsRoot, entry, "entry.tsx")))
    .sort();

  const lines = [
    "/* This file is generated by scripts/generate-application-loaders.mjs */",
    "",
    'import type { NativeApplicationEntry } from "@/platform/sdk/native-application-contract";',
    "",
    "export const applicationLoaderManifest: Record<",
    "  string,",
    "  () => Promise<{ applicationEntry: NativeApplicationEntry }>",
    "> = {",
    ...applicationDirs.map(
      (dir) => `  ${JSON.stringify(dir)}: () => import("@/applications/${dir}/entry"),`,
    ),
    "};",
    "",
  ];

  return lines.join("\n");
}

const expectedSource = getGeneratedManifestSource();

if (checkMode) {
  const existingSource = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (existingSource !== expectedSource) {
    console.error(
      "application loader manifest is stale; run `npm run generate:application-loaders`.",
    );
    process.exit(1);
  }
  process.exit(0);
}

fs.writeFileSync(outputPath, expectedSource, "utf8");
